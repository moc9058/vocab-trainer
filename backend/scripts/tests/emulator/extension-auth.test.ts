import { test } from 'node:test';
import assert from 'node:assert/strict';
import { Firestore } from '@google-cloud/firestore';
import { FirestoreExtensionAuthStore, digest, secret } from '../../../src/extension-auth.js';
import { loadAuthConfig } from '../../../src/auth-config.js';
const host = process.env.FIRESTORE_EMULATOR_HOST;
if (!host || !/^(localhost|127\.0\.0\.1):\d+$/.test(host)) throw new Error('Local emulator is required');
Object.assign(process.env, { GOOGLE_CLIENT_ID: 'test', GOOGLE_CLIENT_SECRET: 'test-secret', OAUTH_REDIRECT_URI: 'https://app.example/api/auth/callback', SESSION_SECRET: 'test-only-session-secret', ALLOWED_EMAILS: 'owner@example.test' });
await loadAuthConfig();
const db = new Firestore({ projectId: 'demo-vocab-safari', databaseId: '(default)' });
const a = new FirestoreExtensionAuthStore(db), b = new FirestoreExtensionAuthStore(db);
test('PKCE approvals and token claims are atomic across instances, hashed, expiring and revocable', async () => {
  const id = secret(), verifier = secret(), state = secret(), user = { email: 'owner@example.test' };
  await a.start(id, { challenge: digest(verifier), code: 'TESTCODE', state, expiresAt: Date.now() + 60000 });
  assert.equal(await b.exchange(id, verifier, state), 'pending');
  assert.equal(await b.exchange(id, secret(), state), null);
  assert.equal(await b.exchange(id, verifier, secret()), null);
  assert.equal(await b.approve(id, 'WRONG', user), false);
  const approvals = await Promise.all([a.approve(id, 'TESTCODE', user), b.approve(id, 'TESTCODE', user)]);
  assert.equal(approvals.filter(Boolean).length, 1);
  const results = await Promise.all([a.exchange(id, verifier, state), b.exchange(id, verifier, state)]);
  const successes = results.filter(r => r && r !== 'pending');
  assert.equal(successes.length, 1);
  const { token } = successes[0] as { token: string };
  assert.equal((await b.read(token))?.user.email, user.email);
  assert.equal((await db.collection('extension_auth_sessions').doc(token).get()).exists, false);
  const idHash = digest(token.slice(4));
  assert.equal((await a.list(user.email)).some(s => s.id === idHash), true);
  await a.revokeOwned(idHash, 'another@example.test'); assert.ok(await b.read(token));
  await a.revokeOwned(idHash, user.email); assert.equal(await b.read(token), null);
  const expired = secret(); await a.start(expired, { challenge: digest(verifier), code: 'EXPIRED', state, expiresAt: 1 });
  assert.equal(await b.request(expired), null); assert.equal(await b.exchange(expired, verifier, state), null);
  const blocked = secret(); await a.start(blocked, { challenge: digest(verifier), code: 'DISALLOW', state, expiresAt: Date.now() + 60000 });
  await a.approve(blocked, 'DISALLOW', { email: 'removed@example.test' });
  assert.equal(await b.exchange(blocked, verifier, state), null);
  const limitKey = secret(); const limits = await Promise.all(Array.from({ length: 16 }, () => a.limit(limitKey)));
  assert.equal(limits.filter(Boolean).length, 15);
  await db.terminate();
});
