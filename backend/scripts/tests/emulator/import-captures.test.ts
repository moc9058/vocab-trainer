import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import Fastify from 'fastify';
import sensible from '@fastify/sensible';
if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Requires emulator');
process.env.FIRESTORE_PROJECT = 'demo-import-captures'; process.env.FIRESTORE_DATABASE_ID = '(default)';
const { db } = await import('../../../src/firestore.js');
const { default: routes } = await import('../../../src/routes/import.js');
await db.doc('languages/chinese').set({ wordCount: 0, topics: [] });
const app = Fastify(); await app.register(sensible); await app.register(routes, { prefix: '/api/import' });
const base = '/api/import/chinese/sessions';
const origin = { version: 1, method: 'shared-image', sourceKind: 'comment', textConfirmed: true, sourceLabel: '小红书' };
const payload = (ingestionId = randomUUID()) => ({ ingestionId, text: '虽然很忙，但我还是来了。', paragraphs: [], items: [], analyzeAsJob: true, sourceOrigin: origin, groupBNames: ['读过的内容'] });
test('concurrent source creation and lost acknowledgements reuse a receipt; edits and deletes are safe', async () => {
  const request = payload();
  const first = await Promise.all([1, 2, 3].map(() => app.inject({ method: 'POST', url: base, payload: request })));
  assert.deepEqual(first.map(r => r.statusCode).sort(), [200, 200, 201], first.map(r => r.body).join('\n'));
  const id = first[0].json().id;
  assert.ok(first.every(r => r.json().id === id));
  const saved = await app.inject({ method: 'PUT', url: `${base}/${id}`, payload: { title: 'edited', contentRevision: 0, analysisCheckpoint: 0, analysisRevision: 0 } });
  assert.equal(saved.statusCode, 200, saved.body);
  const replay = await app.inject({ method: 'POST', url: base, payload: request });
  assert.equal(replay.statusCode, 200); assert.equal(replay.json().title, 'edited');
  assert.deepEqual(replay.json().sourceOrigin, origin);
  const conflict = await app.inject({ method: 'POST', url: base, payload: { ...request, text: '不同的文章。' } });
  assert.equal(conflict.statusCode, 409);
  const overwrite = await app.inject({ method: 'PUT', url: `${base}/${id}`, payload: { contentRevision: 1, sourceOrigin: { ...origin, sourceLabel: 'changed' } } });
  assert.equal(overwrite.statusCode, 400);
  const list = await app.inject(base); assert.deepEqual(list.json().sessions.find((s: any) => s.id === id).sourceOrigin, origin);
  assert.equal((await app.inject({ method: 'DELETE', url: `${base}/${id}` })).statusCode, 200);
  const deleted = await app.inject({ method: 'POST', url: base, payload: request }); assert.equal(deleted.statusCode, 410);
});
test('source validation rejects unconfirmed metadata and malformed meaning ranges before writing', async () => {
  const bad = await app.inject({ method: 'POST', url: base, payload: { ...payload(), sourceOrigin: { ...origin, textConfirmed: false } } });
  assert.equal(bad.statusCode, 400);
  const legacy = await app.inject({ method: 'POST', url: base, payload: { text: '测试。', paragraphs: [], items: [], groupBNames: [] } });
  assert.equal(legacy.statusCode, 201);
  const invalid = await app.inject({ method: 'PUT', url: `${base}/${legacy.json().id}`, payload: { paragraphs: [{ sentences: [{ index: 0, text: '测试。', readingAnalysis: { version: 1, sourceText: '测试。', comprehension: { meaningUnits: { version: 1, units: [{ text: '测试。', range: { start: 0, end: 1 }, meaning: 'test', role: 'statement' }], flow: 'x' } } } }] }] } });
  assert.equal(invalid.statusCode, 400);
});
after(async () => { await app.close(); await db.recursiveDelete(db.collection('import_sessions')); await db.recursiveDelete(db.collection('import_ingestion_receipts')); await db.terminate(); });
